function write_report(summary,dataset,cfg)
%WRITE_REPORT Machine-generated preliminary outcomes; do not predeclare improvement.
file=fullfile(cfg.outputDir,'PRELIMINARY_RESULTS.md');
fid=fopen(file,'w','n','UTF-8'); assert(fid>=0,'Cannot create results report.');
cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'# Preliminary experiment results\n\n');
fprintf(fid,'Generated by MATLAB %s. Dataset: %s; listener: %s.\n\n',version,dataset.database,dataset.subject);
fprintf(fid,'HRIR backend: %s. Sampling rate: %g Hz.\n\n',dataset.backend,dataset.fs);
fprintf(fid,['Target requested azimuth: %g degrees. %d supplied speech pairs. ' ...
    'Calibration: %.2f s target-silent prefix. Cue tolerances: %.1f dB and %.2f rad.\n\n'], ...
    cfg.targetAzimuth,numel(cfg.targetFiles),cfg.calibrationDuration,cfg.sigmaILDdB,cfg.sigmaIPDrad);
fprintf(fid,['Values below are mean SI-SDR improvement and sample SD across pairs. ' ...
    'Negative values indicate worse SI-SDR than the unprocessed mixture. ' ...
    'They are preliminary observations, not evidence of statistical significance.\n\n']);
fprintf(fid,'| Requested angle | Actual angle | Input SNR | Method | SI-SDRi mean | SD | n |\n');
fprintf(fid,'|---:|---:|---:|---|---:|---:|---:|\n');
for k=1:height(summary)
    fprintf(fid,'| %.1f | %.2f | %.1f | %s | %.3f | %.3f | %d |\n', ...
        summary.RequestedSeparationDeg(k),summary.ActualSeparationDeg_Mean(k), ...
        summary.InputSNRdB(k),summary.Method(k),summary.SISDRImprovementdB_Mean(k), ...
        summary.SISDRImprovementdB_SD(k),summary.NumPairs(k));
end
fprintf(fid,['\nSee `metrics_per_condition.csv` for distortion-aware SNR, SI-SDR, ' ...
    'fixed-mask SIR, ILD/IPD errors and cue energy coverage. ' ...
    '`directions.csv` records the actual measured source directions.\n\n']);
fprintf(fid,['The estimated masks do not use clean-source spectra. The oracle power-ratio ' ...
    'mask uses both known components and is a reference, not a deployable method or a strict ' ...
    'upper bound on SI-SDR. Competing speech is nonstationary, so the simple Wiener noise ' ...
    'estimator can fail. Multiplying masks can suppress desired speech as well as interference.\n\n']);
fprintf(fid,['A shared nonnegative mask preserves the mixture interaural ratio before resynthesis; ' ...
    'this does not restore clean-target cues in overlapping bins. Cue metrics reanalyse the ' ...
    'waveforms, exclude reference silence, and must be interpreted with coverage.\n\n']);
fprintf(fid,['Stage 2 folds binaural estimates to mono and renders them with new measured HRIRs. ' ...
    'Its references use the identical fold-down of the clean binaural components, so old HRIR ' ...
    'colouration is matched. This is an application demonstration, not clean dry-source recovery.\n']);
end
